#!/usr/bin/env node
/**
 * Writes .cache/curriculum/sk-seed.sql: INSERT statements for scripts/curriculum/schema.sql,
 * from src/data/curriculum/sk.json. Re-running the seed replaces the previous import.
 *
 *   node scripts/curriculum/export-sql.mjs
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const data = JSON.parse(readFileSync(join(APP, "src", "data", "curriculum", "sk.json"), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (list, type) => `array[${list.map(q).join(", ")}]::${type}[]`;
const row = (values) => `(${values.join(", ")})`;

const out = ["-- Generated by scripts/curriculum/export-sql.mjs. Do not edit; re-run it.", "begin;", "delete from course;", "delete from curriculum_import;"];
out.push(`insert into curriculum_import (id, jurisdiction, imported_on, importer, source_site, source_csv) values (1, 'SK', ${q(data.importedOn)}, ${q(data.importer)}, ${q(data.sources.site)}, ${q(data.sources.csv)});`);

for (const c of data.courses) {
  out.push(
    `insert into course (id, curriculum_id, import_id, name, subject, levels, version, preliminary, renewal, url, outcomes_url, page_sha256, csv_files, problem) values ${row([q(c.id), q(c.curriculumId), "1", q(c.name), q(c.subject), arr(c.levels, "integer"), q(c.version), q(c.preliminary), q(c.renewal), q(c.url), q(c.outcomesUrl), q(c.pageSha256), arr(c.csvFiles, "text"), q(c.problem)])};`,
  );
  c.units.forEach((u, i) => out.push(`insert into unit (id, course_id, oc_id, name, level, url, position) values ${row([q(u.id), q(c.id), q(u.ocId), q(u.name), q(u.level), q(u.url), q(i)])};`));
  c.outcomes.forEach((o, i) => {
    out.push(
      `insert into outcome (id, course_id, unit_id, oc_id, code, statement, printed_with, level, url, fingerprint, status, csv, guidance, notes, position) values ${row([q(o.id), q(c.id), q(o.unitId), q(o.ocId), q(o.code), q(o.statement), q(o.printedWith), q(o.level), q(o.url), q(o.fingerprint), q(o.status), q(o.csv), arr(o.guidance, "text"), arr(o.notes, "text"), q(i)])};`,
    );
    const seen = new Map();
    o.indicators.forEach((ind, j) => {
      const n = (seen.get(ind.label) ?? 0) + 1;
      seen.set(ind.label, n);
      out.push(`insert into indicator (id, outcome_id, label, text, position) values ${row([q(`${o.id}-${ind.label}${n > 1 ? `-${n}` : ""}`), q(o.id), q(ind.label), q(ind.text), q(j)])};`);
    });
  });
}
out.push("commit;", "");

const dir = join(APP, ".cache", "curriculum");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "sk-seed.sql"), out.join("\n"), "utf8");
console.log(`Wrote ${join(dir, "sk-seed.sql")} (${data.courses.length} courses).`);
